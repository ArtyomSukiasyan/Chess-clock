// Builds ../web and inlines its JS/CSS into a single HTML string,
// written to src/webApp.ts so the WebView can load it offline (works in Expo Go).
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const webDir = resolve(root, "../web");
const buildDir = join(webDir, "build");
const outFile = join(root, "src/webApp.ts");

if (!process.argv.includes("--skip-build")) {
  execSync("npm run build", { cwd: webDir, stdio: "inherit" });
}

const readAsset = (href) => readFileSync(join(buildDir, href.replace(/^\//, "")), "utf8");

let html = readFileSync(join(buildDir, "index.html"), "utf8");

html = html
  // Icons and manifest are meaningless inside the native app
  .replace(/\s*<link rel="(icon|apple-touch-icon|manifest)"[^>]*>/g, "")
  .replace(/<link rel="stylesheet"[^>]*href="([^"]+)"[^>]*>/g, (_, href) => `<style>${readAsset(href)}</style>`)
  .replace(
    /<script type="module"[^>]*src="([^"]+)"[^>]*><\/script>/g,
    (_, src) => `<script type="module">${readAsset(src).replace(/<\/script/gi, "<\\/script")}</script>`,
  );

if (/(src|href)="\/assets\//.test(html)) {
  throw new Error("Some web assets were not inlined");
}

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(
  outFile,
  `// Generated by scripts/bundle-web.mjs — do not edit. Run \`npm run bundle-web\`.\nexport const webAppHtml = ${JSON.stringify(html)};\n`,
);

console.log(`Wrote ${outFile} (${(html.length / 1024).toFixed(1)} kB)`);
